# farewell.py — 「送別との関連が確認できるレビュー」の判定（Issue #17）
#
# FR-03 のチャット（chat.py）と、FR-02 の商品カードのレビュー表示で、同じ判定を使う。
# 判定が2か所に分かれると、チャットが答える「送別関連のレビューの件数」と、
# カードで優先して表示されるレビューが食い違うため、ここにまとめる。
#
# 判定の方法：レビュー本文に、下の言葉のどれかが含まれていれば送別関連とみなす。
# 利用者が本文を読めば送別との関係を確かめられるものだけを拾う（要件定義書 3章 FR-02「関連が確認できるレビュー」）。

# 送別関連とみなす言葉（2026-11-21 開発DBのレビューで確認して決めた）
#   入れた言葉：送別（送別会を含む）・異動・退職・転勤・定年・産休 … 送り出す場面で使われていた
#   外した言葉：職場 … 「取引先へのお礼に。職場で渡すのにちょうどよかった」のような、お礼の文脈が中心だった
#               餞別 … 開発DBのレビューに1件もなかった
FAREWELL_WORDS = ("送別", "異動", "退職", "転勤", "定年", "産休")


def is_farewell_related(text: str) -> bool:
    """レビュー本文が送別関連か。FAREWELL_WORDS のどれかを含めば True"""
    return any(word in text for word in FAREWELL_WORDS)
